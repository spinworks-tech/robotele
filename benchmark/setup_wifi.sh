#!/usr/bin/env bash
# Sets up, or tears down, the two-host Wi-Fi protocol comparison
# (docs/14-protocol-comparison-wifi.md, benchmark/run_wifi.py).
#
#   benchmark/setup_wifi.sh up     certs, configs, broker, robot-side files
#   benchmark/setup_wifi.sh down   remove all of it again
#
# `up` generates a throwaway certificate set whose robot certificate also
# names both LAN IPs, so MQTT and Zenoh can check the server's name when
# connecting by IP. It never touches the default dev certs in certs/, which
# robot-edge and operator-console keep using outside the benchmark. The set
# includes private keys (a CA key among them), so it lives in the gitignored
# benchmark/results/wifi/ and `down` deletes it: never commit or publish it.
#
# The robot also needs release builds of robot-edge and proto-bench under
# ~/RoboProtocol (add "tools/proto-bench" to its workspace members).
# Hosts must match run_wifi.py's PI / PI_IP / OP_IP; override with the same
# environment variables here.
set -euo pipefail

PI="${PI:-pi@192.168.2.19}"
PI_IP="${PI_IP:-192.168.2.19}"
OP_IP="${OP_IP:-192.168.2.24}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
W="$ROOT/benchmark/results/wifi"
PI_W="/home/pi/RoboProtocol/benchmark-wifi"
BROKER="bench-mosquitto-wifi"

# Zenoh peer config: $1 the listen/connect line, $2 the certs dir, $3 the identity.
zenoh_config() {
    cat <<EOF
// Wi-Fi protocol comparison: Zenoh peer-to-peer over TLS with mutual auth,
// robot listening, operator connecting by IP (generated by setup_wifi.sh).
{
  mode: "peer",
  $1
  scouting: { multicast: { enabled: false }, gossip: { enabled: false } },
  transport: {
    link: {
      tls: {
        root_ca_certificate: "$2/dev-ca/ca.crt",
        listen_certificate: "$2/$3/$3.crt",
        listen_private_key: "$2/$3/$3.key",
        connect_certificate: "$2/$3/$3.crt",
        connect_private_key: "$2/$3/$3.key",
        enable_mtls: true,
        verify_name_on_connect: true,
      },
    },
  },
}
EOF
}

up() {
    mkdir -p "$W"
    (cd "$ROOT" && cargo run --quiet --release -p dev-certs -- --out-dir "$W/certs" \
        --robot-san "$PI_IP" --robot-san "$OP_IP" >/dev/null)
    # mosquitto runs as its own user inside the container and must read the key.
    chmod 644 "$W"/certs/*/*.key
    zenoh_config 'listen: { endpoints: ["tls/0.0.0.0:7448"] },' "$PI_W/certs" robot > "$W/zenoh_tls_robot.json5"
    zenoh_config "listen: { endpoints: [] }, connect: { endpoints: [\"tls/$PI_IP:7448\"] }," "$W/certs" operator \
        > "$W/zenoh_tls_operator.json5"
    cat > "$W/mosquitto.conf" <<EOF
per_listener_settings false
allow_anonymous true
listener 1884
listener 8884
cafile /certs/dev-ca/ca.crt
certfile /certs/robot/robot.crt
keyfile /certs/robot/robot.key
require_certificate true
tls_version tlsv1.3
EOF
    # The robot gets its own identity and the CA certificate, never the CA key.
    ssh -o BatchMode=yes "$PI" "mkdir -p $PI_W/certs/dev-ca $PI_W/certs/robot"
    scp -q "$W/certs/dev-ca/ca.crt" "$PI:$PI_W/certs/dev-ca/"
    scp -q "$W/certs/robot/robot.crt" "$W/certs/robot/robot.key" "$PI:$PI_W/certs/robot/"
    scp -q "$W/zenoh_tls_robot.json5" "$PI:$PI_W/"
    docker rm -f "$BROKER" >/dev/null 2>&1 || true
    docker run -d --name "$BROKER" --network host \
        -v "$W/mosquitto.conf:/mosquitto/config/mosquitto.conf:ro" -v "$W/certs:/certs:ro" \
        eclipse-mosquitto:2 >/dev/null
    echo "ready: certs and configs in $W, robot files in $PI:$PI_W, broker $BROKER on 1884/8884"
}

down() {
    docker rm -f "$BROKER" >/dev/null 2>&1 || true
    rm -rf "$W/certs" "$W/zenoh_tls_robot.json5" "$W/zenoh_tls_operator.json5" "$W/mosquitto.conf"
    ssh -o BatchMode=yes "$PI" "rm -rf $PI_W"
    echo "removed: broker, generated certs and configs here and on $PI (results kept)"
}

case "${1:-}" in
    up) up ;;
    down) down ;;
    *) echo "usage: $0 up|down" >&2; exit 2 ;;
esac
